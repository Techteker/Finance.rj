export const TRANSLATIONS: Record<LangCode, Dictionary> = {
  en: EN,
  hi: HI,
  mr: MR,
  gu: GU,
  ta: TA,
  te: TE,
};

export function isSupportedLang(value: unknown): value is LangCode {
  return typeof value === 'string' && value in TRANSLATIONS;
}

export function normalizeLang(value: unknown): LangCode {
  if (typeof value !== 'string') return 'en';
  const cleaned = value.trim().toLowerCase().split(/[-_]/)[0];
  return isSupportedLang(cleaned) ? cleaned : 'en';
}

export function getLanguageOption(lang: LangCode): LanguageOption {
  return LANGUAGES.find((item) => item.code === lang) ?? LANGUAGES[0];
}

export function translate(
  lang: LangCode,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const dict = TRANSLATIONS[lang] ?? EN;
  const raw = dict[key] || EN[key] || key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, token: string) =>
    token in vars ? String(vars[token]) : `{${token}}`,
  );
}

function lookupDynamic(lang: LangCode, prefix: string, slug: string, fallback: string): string {
  const key = `${prefix}.${slug}` as TranslationKey;
  if (key in EN) return translate(lang, key);
  return fallback;
}

export const translateCategory = (lang: LangCode, slug: string, fallback: string) =>
  lookupDynamic(lang, 'cat', slug, fallback);

export const translateCategoryDesc = (lang: LangCode, slug: string, fallback: string) =>
  lookupDynamic(lang, 'catDesc', slug, fallback);

export const translateNewsCategory = (lang: LangCode, slug: string, fallback: string) =>
  lookupDynamic(lang, 'newsCat', slug, fallback);

export const translateOfferCategory = (lang: LangCode, slug: string, fallback: string) =>
  lookupDynamic(lang, 'offerCat', slug, fallback);

export const translateCalculator = (lang: LangCode, slug: string, fallback: string) =>
  lookupDynamic(lang, 'calc', slug, fallback);
